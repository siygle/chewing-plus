#!/usr/bin/env python3
"""Build data/plus-phrases.txt from libchewing-data's dict/chewing/tsi.csv.

    python3 scripts/make-phrases.py path/to/tsi.csv > data/plus-phrases.txt

One line per phrase of two or more characters: phrase, frequency, and the
first Bopomofo symbol of each syllable (the abbreviation), tab separated.
Highest frequency wins when a phrase has several readings. Sorted by phrase
so the file diffs cleanly.
"""
import sys


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    best = {}
    version = ""
    with open(sys.argv[1], encoding="utf-8") as fh:
        for line in fh:
            if line.startswith("# dc:identifier,"):
                version = line.split(",")[1]
            if line.startswith("#"):
                continue
            parts = line.rstrip("\n").split(",")
            if len(parts) < 3:
                continue
            word, freq, phone = parts[0], parts[1], parts[2]
            try:
                freq = int(freq)
            except ValueError:
                continue
            syllables = phone.split(" ")
            if len(word) < 2 or len(syllables) != len(word) or "\t" in word:
                continue
            abbr = "".join(s[0] for s in syllables if s)
            if len(abbr) != len(word):
                continue
            if word not in best or freq > best[word][0]:
                best[word] = (freq, abbr)
    out = sys.stdout
    out.write("# Phrases from libchewing-data dict/chewing/tsi.csv"
              f" ({version}), LGPL-2.1-or-later, libchewing Core Team.\n")
    out.write("# Generated by scripts/make-phrases.py; do not edit.\n")
    out.write("# phrase<TAB>frequency<TAB>first Bopomofo of each syllable\n")
    for word in sorted(best):
        freq, abbr = best[word]
        out.write(f"{word}\t{freq}\t{abbr}\n")


if __name__ == "__main__":
    main()
