#!/usr/bin/env python3
"""Generate data/plus-english.txt from a SCOWL/ESDB wordlist (MIT-like),
optionally merged with curated modern English word list(s).

Usage:
    python3 scripts/make-english-words.py <esdb-words.txt> \\
        [--extra data/plus-english-modern.txt] > data/plus-english.txt

Base wordlist source:
    https://app.aspell.net/create
    (max_size=60, spelling=US, variant_level=1, diacritic=strip, special=hacker)

Keeps ASCII words of 2-30 characters (apostrophe forms such as "AA's" dropped).
When a word appears in several casings ("apple", "Apple"), all are kept; the
engine uses the canonical casing for all-lowercase input when unambiguous and
offers every casing in the [EN] candidate list.

Sorted in ASCII order so the file diffs cleanly.
"""
import argparse
import re
import sys

# ASCII word of 2-30 chars, containing at least one ASCII letter.
WORD_RE = re.compile(r"^(?=.*[A-Za-z])[A-Za-z0-9][A-Za-z0-9.+#-]{1,29}$")


def read_wordlist(path, skip_esdb_header=False):
    words = []
    with open(path, encoding="utf-8") as fh:
        lines = fh.readlines()
    start = 0
    if skip_esdb_header:
        # Inline downloads from app.aspell.net/create include a preamble
        # terminated by a line containing only "---".
        for i, raw in enumerate(lines[:100]):
            if raw.strip() == "---":
                start = i + 1
                break
    for raw in lines[start:]:
        s = raw.strip()
        if not s or s.startswith("#"):
            continue
        if WORD_RE.match(s):
            words.append(s)
    return words


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--size",
        default="60",
        help="SCOWL/ESDB size label for the generated header (default: 60)",
    )
    parser.add_argument(
        "--extra",
        action="append",
        default=[],
        metavar="PATH",
        help="Optional curated word list(s) to merge (one word per line)",
    )
    parser.add_argument("wordlist", help="Path to SCOWL/ESDB wordlist file")
    args = parser.parse_args()

    words = set(read_wordlist(args.wordlist, skip_esdb_header=True))
    base_count = len(words)

    extra_sources = []
    for extra_path in args.extra:
        extra_words = read_wordlist(extra_path, skip_esdb_header=False)
        before = len(words)
        words.update(extra_words)
        added = len(words) - before
        extra_sources.append(f"{extra_path} (LGPL-2.1-or-later)")
        print(
            f"make-english-words: +{extra_path} added={added} (from {len(extra_words)})",
            file=sys.stderr,
        )

    ordered = sorted(words)
    print(
        f"make-english-words: base={base_count}, total={len(ordered)}",
        file=sys.stderr,
    )

    out = sys.stdout
    out.write(
        f"# English words from SCOWL/ESDB (size {args.size}, US, hacker),"
        " Copyright 2000-2026 Kevin Atkinson.\n"
    )
    if extra_sources:
        out.write(
            "# See data/LICENSE.scowl. Merged with "
            + ", ".join(extra_sources)
            + ".\n"
        )
    else:
        out.write("# See data/LICENSE.scowl.\n")
    out.write("# Generated by scripts/make-english-words.py; do not edit.\n")
    out.write(
        "# Custom words: ~/.local/share/chewing-plus/plus-english.txt (Linux)"
        " or ~/Library/Application Support/ChewingPlus/plus-english.txt (macOS).\n"
    )
    for w in ordered:
        out.write(w + "\n")


if __name__ == "__main__":
    main()
